/** 后台送来的一句：认识的换成英文，不认识的原样。 */
function tr(s) {
  if (LANG.zh || typeof s !== 'string' || !CJK.test(s)) return s;
  const t = s.trim();
  if (SRV_WORD[t]) return SRV_WORD[t];
  for (const [re, to] of SRV) {
    const m = t.match(re);
    if (m) return to(...m);
  }
  // 几句用「，」「；」连起来的：一句句换
  if (/[，；]/.test(t)) {
    const parts = t.split(/([，；])/);
    const out = parts.map((p, i) => (p === '，' ? ', ' : p === '；' ? '; ' : i && /^[A-Z][a-z]/.test(tr(p)) && tr(p) !== p ? tr(p)[0].toLowerCase() + tr(p).slice(1) : tr(p)));
    if (out.some((p, i) => p !== parts[i] && parts[i] !== '，' && parts[i] !== '；')) return out.join('');
  }
  return s;
}
