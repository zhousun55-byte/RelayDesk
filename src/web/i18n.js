/** 界面上的字：`T\`第 ${n} 棒\``。 */
function T(strs, ...vals) {
  const zh = () => strs.reduce((a, s, i) => a + vals[i - 1] + s);
  if (LANG.zh) return zh();
  const key = strs.join('{}');
  const en = EN[key];
  if (en === undefined) {
    T.missing.add(key);
    return zh();
  }
  if (typeof en === 'function') return en(...vals);
  let i = 0;
  return en.replace(/\{(\d*)\}/g, (_, n) => String(vals[n === '' ? i++ : Number(n)]));
}
T.missing = new Set();

/** 存在表里的一句（不是写在代码里的字面量）；ctx：同一个词在别处英文不一样时，表里写成「ctx|词」。 */
function L(s, ctx) {
  if (!LANG.zh && ctx && EN[`${ctx}|${s}`] !== undefined) return EN[`${ctx}|${s}`];
  return EN[s] === undefined && !LANG.zh && !CJK.test(s) ? s : T([s]);
}

