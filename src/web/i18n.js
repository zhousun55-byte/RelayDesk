/* 网页的两种语言：中文（原文）和英文。
   界面上的字在 app.js 里照常写中文，套一层 T`…`：中文原样拼，英文按下面的 EN 表换（`{}` 是原文里 ${…} 的位置，
   英文里写 {0}、{1} 可以换顺序；要按数量变单复数的写成函数）。表里没有的，英文里也先显示中文。
   接力台后台送来的字（状态、结论、验收、恢复时间……）套 tr(…)：先整句对照，再按 SRV 的句式换，都不认识就原样。
   AI 写的交接、人写的任务不翻。换语言记在本机浏览器里，重新载入一次（app.js 的 switchLang）。 */

const LANG = (() => {
  let v = null;
  try {
    v = localStorage.getItem('relay.lang');
  } catch {
    /* 浏览器不让用本地存储：按浏览器的语言 */
  }
  if (v !== 'zh' && v !== 'en') v = typeof navigator === 'undefined' || /^zh\b/i.test(navigator.language || '') ? 'zh' : 'en';
  if (typeof document === 'undefined') return { now: v, zh: v === 'zh' };
  document.documentElement.lang = v === 'zh' ? 'zh-CN' : 'en';
  // 刚换了语言、重新载入：先藏着，app.js 摆好了再淡进来（万一没画出来，一秒半后也露出来）
  try {
    if (sessionStorage.getItem('relay.carry')) {
      document.documentElement.classList.add('lang-in');
      setTimeout(() => document.documentElement.classList.remove('lang-in'), 1500);
    }
  } catch {
    /* 没有会话存储：直接显示 */
  }
  return { now: v, zh: v === 'zh' };
})();

